-- Hyprland entry point (Lua config, Hyprland 0.55+). Replaces hyprland.conf.
-- Layers load in this order; later layers win. Layout: ~/.syna/guides/hyprland-config.md
--   1 rice defaults  2 theme colors  3 personal overrides  4 machine-local (*.local.lua)  5 theme geometry
-- Paths are absolute on purpose: rice defaults and personal files share module names
-- (input, looknfeel, autostart, windows), and require() loads a given name only once.

local home = os.getenv("HOME")
local hypr = home .. "/.config/hypr"
local defaults = home .. "/.config/rice/defaults/hypr"
local theme = home .. "/.config/themes/current"

-- Optional files (machine-local, generated): a missing file is fine, an error inside one is not.
function syna_optional(path)
  local ok, err = pcall(require, path)
  if not ok and not tostring(err):find("not found", 1, true) then
    error(err, 0)
  end
end

-- 1. Rice defaults
require(defaults .. "/autostart")
require(defaults .. "/bindings/media")
require(defaults .. "/bindings/clipboard")
require(defaults .. "/bindings/tiling-v2")
require(defaults .. "/bindings/utilities")
require(defaults .. "/envs")
require(defaults .. "/looknfeel")
require(defaults .. "/input")
require(defaults .. "/windows")

-- 2. Theme colors (generated by syna-theme-engine)
syna_optional(theme .. "/hyprland")

-- 3. Personal overrides (each personal file loads its own *.local.lua)
require(hypr .. "/monitors")
require(hypr .. "/input")
require(hypr .. "/bindings")
require(hypr .. "/looknfeel")
require(hypr .. "/autostart")
require(hypr .. "/windows")

hl.config({
  misc = {
    vrr = 2, -- 0=off, 1=on, 2=fullscreen only (fixes desktop flickering)
  },
})

-- 5. Theme window geometry (generated by syna-theme-engine)
syna_optional(theme .. "/window-geometry")
